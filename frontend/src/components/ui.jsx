// Direction-aware amount cell for ledgers: 'in' (green +) or 'out' (red -)
export function Amt({ value, dir }) {
  const sign = dir === 'in' ? '+' : '−';
  return <span className={dir === 'in' ? 'td-amt-in' : 'td-amt-out'}>{sign} {fmt(value)}</span>;
}

