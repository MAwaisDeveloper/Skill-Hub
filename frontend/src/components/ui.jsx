export function InvoiceModal({ kind, id, reference, onClose }) {
  const { session } = useAppSafe();
  const [inv, setInv] = useState(null);
  const [error, setError] = useState('');
  useEffect(() => {
    let live = true;
    const url = kind === 'topup' ? `/invoices/topup/${encodeURIComponent(reference)}`
      : kind === 'booking' ? `/invoices/booking/${id}`
      : kind === 'payout' ? `/invoices/payout/${id}`
      : kind === 'withdrawal' ? `/invoices/withdrawal/${id}`
      : `/invoices/penalty/${id}`;
    api.get(url, session?.token).then((d) => { if (live) setInv(d); }).catch((e) => { if (live) setError(e.message); });
    return () => { live = false; };
  }, [kind, id, reference, session?.token]);

  if (!kind) return null;
  return (
    <div style={{ position: 'fixed', inset: 0, background: 'rgba(7,20,14,.55)', zIndex: 60, display: 'flex', alignItems: 'center', justifyContent: 'center', padding: 16 }} onClick={onClose}>
      <div className="card" style={{ maxWidth: 560, width: '100%', maxHeight: '88vh', overflowY: 'auto' }} onClick={(e) => e.stopPropagation()}>
        {error && <div className="alert error">{error}</div>}
        {!inv && !error && <p className="muted">Loading invoice…</p>}
        {inv && (
          <>
            <div className="row spread">
              <h2 style={{ margin: 0 }}>🧾 {inv.invoice_number}</h2>
              <span className={`badge ${inv.status === 'completed' || inv.status === 'released' ? 'verified' : 'status'}`}>{inv.status}</span>
            </div>
            <p className="muted" style={{ marginTop: 2 }}>{inv.type} · {new Date(inv.date).toLocaleString()}</p>
            <table style={{ margin: '10px 0' }}>
              <tbody>
                <tr><th style={{ width: 130 }}>From</th><td>{inv.from}</td></tr>
                <tr><th>To</th><td>{inv.to}</td></tr>
                <tr><th>Method</th><td>{inv.method}</td></tr>
                <tr><th>Reference</th><td>{inv.reference}</td></tr>
              </tbody>
            </table>
            <table>
              <thead><tr><th>Description</th><th style={{ textAlign: 'right' }}>Amount (Rs)</th></tr></thead>
              <tbody>
                {inv.items.map((it, i) => (
                  <tr key={i}><td>{it.description}</td><td style={{ textAlign: 'right', color: it.amount < 0 ? 'var(--danger)' : undefined }}>{new Intl.NumberFormat('en-PK').format(it.amount)}</td></tr>
                ))}
                <tr><td className="muted">Subtotal</td><td style={{ textAlign: 'right' }}>{new Intl.NumberFormat('en-PK').format(inv.subtotal)}</td></tr>
                {inv.fees ? <tr><td className="muted">Platform commission</td><td style={{ textAlign: 'right', color: 'var(--danger)' }}>−{new Intl.NumberFormat('en-PK').format(inv.fees)}</td></tr> : null}
                <tr><th>Total</th><th style={{ textAlign: 'right' }}>Rs {new Intl.NumberFormat('en-PK').format(inv.total)}</th></tr>
              </tbody>
            </table>
            {inv.admin_note && <p className="muted" style={{ fontSize: 13 }}>Admin note: {inv.admin_note}</p>}
            <p className="muted" style={{ fontSize: 12 }}>Generated automatically by Hunar: please retain this invoice for your records.</p>
            <div className="row mt">
              <button className="btn small" onClick={() => window.print()} title="Print this page">🖨 Print</button>
              <button className="btn small secondary" onClick={() => openPrintableInvoice(inv)}>⬇ Download PDF</button>
              <button className="btn small danger" onClick={onClose}>Close</button>
            </div>
          </>
        )}
      </div>
    </div>
  );
}

export function StatusBadge({ status }) {
  if (!status) return null;
  return <span className={`badge ${status}`}>{status.replaceAll('_', ' ')}</span>;
}

// Direction badge: incoming (green), outgoing (red), pending (amber)
export function DirBadge({ dir, label }) {
  const map = { in: ['in', '↑ Incoming'], out: ['out', '↓ Outgoing'], pending: ['pending', '◔ Pending'] };
  const [cls, text] = map[dir] || ['', label || ''];
  return <span className={`badge dir ${cls}`}>{label || text}</span>;
}

// Quick period selector: Latest (default) / This Week / This Month / 3 Months / All + custom range
export function periodRange(period) {
  const now = new Date();
  const to = now.toISOString().slice(0, 10);
  if (period === 'week') {
    const d = new Date(now); d.setDate(d.getDate() - 7);
    return { from: d.toISOString().slice(0, 10), to };
  }
  if (period === 'month') {
    const d = new Date(now); d.setMonth(d.getMonth() - 1);
    return { from: d.toISOString().slice(0, 10), to };
  }
  if (period === 'quarter') {
    const d = new Date(now); d.setMonth(d.getMonth() - 3);
    return { from: d.toISOString().slice(0, 10), to };
  }
  return { from: '', to: '' }; // 'all'
}

