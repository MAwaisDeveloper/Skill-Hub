export function Pagination({ pagination, onPage }) {
  if (!pagination || pagination.total_pages <= 1) return null;
  const { page, total_pages, total } = pagination;
  return (
    <div className="pagination">
      <button className="btn small secondary" disabled={page <= 1} onClick={() => onPage(page - 1)}>‹ Prev</button>
      <span className="muted">Page {page} / {total_pages} · {total} records</span>
      <button className="btn small secondary" disabled={page >= total_pages} onClick={() => onPage(page + 1)}>Next ›</button>
    </div>
  );
}

// Full statement: summary cards + period tabs + filters + paginated ledger.
// Default view: This Week (latest records first). Admin sees all via the same component.
export function StatementView({ fetcher, title = 'Transaction History', subtitle }) {
  const [data, setData] = useState(null);
  const [period, setPeriod] = useState('week'); // latest week by default
  const [filters, setFilters] = useState(() => ({ direction: '', type: '', ...periodRange('week'), page: 1 }));
  const [error, setError] = useState('');
  const [inv, setInv] = useState(null); // { kind, id, reference }

  useEffect(() => {
    let live = true;
    fetcher(filters)
      .then((d) => { if (live) setData(d); })
      .catch((e) => { if (live) setError(e.message); });
    return () => { live = false; };
  }, [filters]);

  const applyPeriod = (p) => {
    setPeriod(p);
    setFilters((f) => ({ ...f, ...periodRange(p), page: 1 }));
  };

  const s = data?.summary;
  return (
    <>
      {error && <div className="alert error">{error}</div>}
      {s && (
        <div className="grid cols-4">
          <div className="card stat"><span className="value td-amt-in">+ {fmt(s.total_in)}</span><span className="label">Total Incoming</span><span className="hint">top-ups + refunds + payouts</span></div>
          <div className="card stat"><span className="value td-amt-out">− {fmt(s.total_out)}</span><span className="label">Total Outgoing</span><span className="hint">holds + releases + penalties</span></div>
          <div className="card stat"><span className="value" style={{ color: '#b7791f' }}>{s.pending_withdrawals ? `${s.pending_withdrawals} · ${fmt(s.pending_withdrawals_amount)}` : '0'}</span><span className="label">Processing Withdrawals</span><span className="hint">being paid out via gateway</span></div>
          <div className="card stat"><span className="value" style={{ color: s.pending_penalty > 0 ? 'var(--danger)' : 'inherit' }}>{s.pending_penalty > 0 ? fmt(s.pending_penalty) : '0'}</span><span className="label">Pending Penalty (owed)</span><span className="hint">auto-deducted from next payout</span></div>
        </div>
      )}
      <div className="card">
        <h2>{title}</h2>
        {subtitle && <p className="muted mb">{subtitle}</p>}
        <div className="filters" style={{ marginBottom: 8 }}>
          {[
            ['week', 'This Week'],
            ['month', 'This Month'],
            ['quarter', 'Last 3 Months'],
            ['all', 'All Time'],
          ].map(([key, label]) => (
            <button key={key} className={`btn small ${period === key ? '' : 'secondary'}`} onClick={() => applyPeriod(key)}>{label}</button>
          ))}
        </div>
        <StatementFilters value={filters} onChange={setFilters} onReset={() => { setPeriod('week'); setFilters({ direction: '', type: '', ...periodRange('week'), page: 1 }); }} />
        {!data && <p className="muted">Loading statement…</p>}
        {data && data.rows.length === 0 && <Empty>No transactions in this period.</Empty>}
        {data && data.rows.length > 0 && (
          <>
            <table>
              <thead>
                <tr><th>Date &amp; Time</th><th>Direction</th><th>Type</th><th>Counterparty</th><th>Booking</th><th>Service</th><th>Amount</th><th>Balance After</th><th>Invoice</th></tr>
              </thead>
              <tbody>
                {data.rows.map((t) => {
                  const dir = ['topup', 'refund', 'payout', 'compensation'].includes(t.type) ? 'in' : 'out';
                  const invKind = t.booking_id ? 'booking' : t.type === 'topup' ? 'topup' : t.type === 'payout' ? 'payout' : t.type === 'penalty' ? 'penalty' : null;
                  return (
                    <tr key={t.id}>
                      <td>{t.created_at?.slice(0, 16)}</td>
                      <td><DirBadge dir={dir} label={dir === 'in' ? 'Incoming' : 'Outgoing'} /></td>
                      <td><span className={`badge ${t.type}`}>{t.type}</span></td>
                      <td>
                        {t.counterparty_role}
                        {t.counterparty_name ? <div className="muted"><b>{t.counterparty_name}</b></div> : null}
                      </td>
                      <td className="muted">{t.booking_code || '—'}</td>
                      <td className="muted">{t.category_name || '—'}</td>
                      <td><Amt value={t.amount} dir={dir} /></td>
                      <td>{fmt(t.balance_after)}</td>
                      <td>
                        {invKind === 'topup' && t.topup_ref ? <button className="btn small secondary" onClick={() => setInv({ kind: 'topup', reference: t.topup_ref })}>🧾</button>
                          : invKind === 'penalty' && t.penalty_id ? <button className="btn small secondary" onClick={() => setInv({ kind: 'penalty', id: t.penalty_id })}>🧾</button>
                          : invKind && t.booking_id ? <button className="btn small secondary" onClick={() => setInv({ kind: invKind, id: t.booking_id })}>🧾</button>
                          : <span className="muted">—</span>}
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
            <Pagination pagination={data.pagination} onPage={(p) => setFilters({ ...filters, page: p })} />
          </>
        )}
      </div>

      {inv && <InvoiceModal kind={inv.kind} id={inv.id} reference={inv.reference} onClose={() => setInv(null)} />}
    </>
  );
}

// Cancel consequence modal: exact breakdown before the user confirms cancellation
const REASONS = [
  'Kaam adhoora / ghalat hua',
  'Professional waqt par nahi aaya',
  'Professional raabta nahi kar raha',
  'Extra paisay ki demand hui',
  'Tabdeeli ke baad masla (offer/price)',
  'Property ko nuqsaan pohancha',
  'Behtari / safai ka masla',
  'Koi aur masla',
];

// Report a Problem modal — prompt() ki jagah proper form (reason dropdown + description).
// Automation-friendly: real <select>/<textarea>, label se accessible.
export function DisputeModal({ bookingCode, onSubmit, onClose, busy = false }) {
  const [reason, setReason] = useState(REASONS[0]);
  const [description, setDescription] = useState('');
  const [localError, setLocalError] = useState('');
  if (!bookingCode) return null;
  const submit = () => {
    if (description.trim().length < 10) { setLocalError('Please describe the problem in a little more detail (at least 10 characters).'); return; }
    setLocalError('');
    onSubmit({ reason, description: description.trim() });
  };
  return (
    <div className="modal-backdrop" onClick={onClose}>
      <div className="modal card" onClick={(e) => e.stopPropagation()} role="dialog" aria-label="Report a Problem">
        <h2>⚠️ Report a Problem: Booking {bookingCode}</h2>
        <p className="muted">Your payment stays safely in escrow until an administrator reviews the case and decides the outcome.</p>
        <label htmlFor="dispute-reason">Problem kis cheez ki hai?</label>
        <select id="dispute-reason" value={reason} onChange={(e) => setReason(e.target.value)} style={{ width: '100%', marginBottom: 10 }}>
          {REASONS.map((r) => <option key={r} value={r}>{r}</option>)}
        </select>
        <label htmlFor="dispute-description">Detail (professional ko nahi, sirf admin dekhega)</label>
        <textarea
          id="dispute-description"
          rows={4}
          placeholder="Kya masla hua — kaam adhoora, raabta nahi, tabdeeli ki ghiar…"
          value={description}
          onChange={(e) => setDescription(e.target.value)}
          style={{ width: '100%' }}
        />
        {localError && <div className="alert error mt">{localError}</div>}
        <div className="row mt">
          <button className="btn danger" onClick={submit} disabled={busy}>{busy ? 'Submitting…' : 'Submit Report'}</button>
          <button className="btn secondary" onClick={onClose}>Cancel</button>
        </div>
      </div>
    </div>
  );
}

